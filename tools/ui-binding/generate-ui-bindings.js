#!/usr/bin/env node

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const GENERATED_MARKER = 'AUTO-GENERATED by tools/ui-binding/generate-ui-bindings.js. DO NOT EDIT.';

const DEFAULT_CONFIG = {
  prefabRoots: ['assets/prefabs/ui'],
  scriptOutputRoot: 'assets/scripts/modules',
  generatedDirName: 'generated',
  requireRootNameMatch: true,
  baseViewPath: 'assets/scripts/core/ui/UIView.ts',
  nodeBinderPath: 'assets/scripts/core/ui/NodeBinder.ts',
  prefixes: {
    node: { type: 'Node', fieldSuffix: 'Node' },
    btn: { type: 'Button', fieldSuffix: 'Button' },
    lbl: { type: 'Label', fieldSuffix: 'Label' },
    rich: { type: 'RichText', fieldSuffix: 'RichText' },
    spr: { type: 'Sprite', fieldSuffix: 'Sprite' },
    toggle: { type: 'Toggle', fieldSuffix: 'Toggle' },
    edit: { type: 'EditBox', fieldSuffix: 'EditBox' },
    scroll: { type: 'ScrollView', fieldSuffix: 'ScrollView' },
    progress: { type: 'ProgressBar', fieldSuffix: 'ProgressBar' },
    slider: { type: 'Slider', fieldSuffix: 'Slider' },
    layout: { type: 'Layout', fieldSuffix: 'Layout' },
    page: { type: 'PageView', fieldSuffix: 'PageView' },
    mask: { type: 'Mask', fieldSuffix: 'Mask' },
    graphics: { type: 'Graphics', fieldSuffix: 'Graphics' },
    anim: { type: 'Animation', fieldSuffix: 'Animation' },
    widget: { type: 'Widget', fieldSuffix: 'Widget' },
  },
};

function main() {
  try {
    const args = parseArgs(process.argv.slice(2));
    if (args.help) {
      printHelp();
      return;
    }

    const configPath = args.config || 'tools/ui-binding/ui-binding.config.json';
    const config = loadConfig(configPath);
    const prefabFiles = args.prefab
      ? [resolveProjectPath(args.prefab)]
      : collectPrefabFiles(config.prefabRoots);

    const expectedGeneratedFiles = new Set();
    const changedFiles = [];
    const failures = [];

    for (const prefabFile of prefabFiles) {
      try {
        const generated = buildGeneratedBinding(prefabFile, config);
        expectedGeneratedFiles.add(generated.outputFile);

        const changed = writeGeneratedFile(generated.outputFile, generated.content, args.check, config);
        if (changed) {
          changedFiles.push(generated.outputFile);
        }
      } catch (error) {
        failures.push(error.message);
      }
    }

    try {
      handleStaleGeneratedFiles(config, expectedGeneratedFiles, args);
    } catch (error) {
      failures.push(error.message);
    }

    if (failures.length > 0) {
      throw new Error(failures.join('\n'));
    }

    if (args.check) {
      console.log(`[ui-binding] Checked ${prefabFiles.length} prefab(s).`);
      return;
    }

    const changedText = changedFiles.length === 0
      ? 'no file changes'
      : `${changedFiles.length} generated file(s) updated`;
    console.log(`[ui-binding] Generated bindings for ${prefabFiles.length} prefab(s), ${changedText}.`);
  } catch (error) {
    console.error(`[ui-binding] ${error.message}`);
    process.exit(1);
  }
}

function parseArgs(argv) {
  const args = {
    check: false,
    prune: false,
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];

    if (arg === '--help' || arg === '-h') {
      args.help = true;
      continue;
    }

    if (arg === '--check') {
      args.check = true;
      continue;
    }

    if (arg === '--prune') {
      args.prune = true;
      continue;
    }

    if (arg === '--config' || arg === '-c') {
      args.config = readArgValue(argv, i, arg);
      i += 1;
      continue;
    }

    if (arg === '--prefab' || arg === '-p') {
      args.prefab = readArgValue(argv, i, arg);
      i += 1;
      continue;
    }

    throw new Error(`Unknown argument: ${arg}`);
  }

  return args;
}

function readArgValue(argv, index, name) {
  const value = argv[index + 1];
  if (!value || value.startsWith('-')) {
    throw new Error(`${name} requires a value.`);
  }
  return value;
}

function printHelp() {
  console.log(`Usage:
  node tools/ui-binding/generate-ui-bindings.js --config tools/ui-binding/ui-binding.config.json

Options:
  -c, --config <path>    Binding generation config. Defaults to tools/ui-binding/ui-binding.config.json
  -p, --prefab <path>    Generate or check one prefab only.
      --check            Verify generated files are up to date without writing.
      --prune            Remove stale generated files with this tool's generated marker.
  -h, --help             Show this help.
`);
}

function loadConfig(configPath) {
  const resolvedConfigPath = resolveProjectPath(configPath);
  assertFileExists(resolvedConfigPath, 'UI binding config file does not exist');
  const userConfig = readJson(resolvedConfigPath);

  const merged = {
    ...DEFAULT_CONFIG,
    ...userConfig,
    prefixes: {
      ...DEFAULT_CONFIG.prefixes,
      ...(userConfig.prefixes || {}),
    },
  };

  return normalizeConfig(merged);
}

function normalizeConfig(config) {
  const prefabRoots = normalizePathArray(config.prefabRoots, 'prefabRoots');
  const scriptOutputRoot = resolveProjectPath(assertNonEmptyString(config.scriptOutputRoot, 'scriptOutputRoot is required.'));
  const generatedDirName = assertNonEmptyString(config.generatedDirName, 'generatedDirName is required.');
  const baseViewPath = resolveProjectPath(assertNonEmptyString(config.baseViewPath, 'baseViewPath is required.'));
  const nodeBinderPath = resolveProjectPath(assertNonEmptyString(config.nodeBinderPath, 'nodeBinderPath is required.'));

  if (!config.prefixes || typeof config.prefixes !== 'object' || Array.isArray(config.prefixes)) {
    throw new Error('prefixes must be an object.');
  }

  const prefixes = Object.entries(config.prefixes).map(([prefix, entry]) => {
    const normalizedPrefix = assertNonEmptyString(prefix, 'Binding prefix is required.');
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) {
      throw new Error(`Binding prefix '${normalizedPrefix}' config must be an object.`);
    }

    const type = assertNonEmptyString(entry.type, `Binding prefix '${normalizedPrefix}' type is required.`);
    const fieldSuffix = assertNonEmptyString(
      entry.fieldSuffix || type,
      `Binding prefix '${normalizedPrefix}' fieldSuffix is required.`,
    );
    const component = entry.component === null
      ? null
      : assertNonEmptyString(entry.component || (type === 'Node' ? 'Node' : type), `Binding prefix '${normalizedPrefix}' component is required.`);

    return {
      prefix: normalizedPrefix,
      type,
      fieldSuffix,
      component,
    };
  });

  if (prefixes.length === 0) {
    throw new Error('At least one binding prefix is required.');
  }

  prefixes.sort((left, right) => right.prefix.length - left.prefix.length);

  return {
    prefabRoots,
    scriptOutputRoot,
    generatedDirName,
    requireRootNameMatch: config.requireRootNameMatch !== false,
    baseViewPath,
    nodeBinderPath,
    prefixes,
  };
}

function normalizePathArray(value, label) {
  if (!Array.isArray(value) || value.length === 0) {
    throw new Error(`${label} requires a non-empty array.`);
  }

  return value.map((item) => resolveProjectPath(assertNonEmptyString(item, `${label} item is required.`)));
}

function readJson(filePath) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch (error) {
    throw new Error(`Invalid JSON '${formatPath(filePath)}': ${error.message}`);
  }
}

function collectPrefabFiles(prefabRoots) {
  const files = [];
  for (const root of prefabRoots) {
    if (!fs.existsSync(root)) {
      continue;
    }
    files.push(...collectFiles(root, (filePath) => filePath.endsWith('.prefab')));
  }
  return files.sort((left, right) => left.localeCompare(right));
}

function collectFiles(dir, predicate) {
  const result = [];
  const entries = fs.readdirSync(dir, { withFileTypes: true });

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      result.push(...collectFiles(fullPath, predicate));
      continue;
    }

    if (entry.isFile() && predicate(fullPath)) {
      result.push(fullPath);
    }
  }

  return result;
}

function buildGeneratedBinding(prefabFile, config) {
  const prefab = parsePrefab(prefabFile, config);
  const outputFile = resolveOutputFile(prefabFile, config);
  const content = renderBindingFile(prefab, outputFile, config);

  return {
    outputFile,
    content,
  };
}

function parsePrefab(prefabFile, config) {
  assertFileExists(prefabFile, 'Prefab file does not exist');

  let records;
  try {
    records = JSON.parse(fs.readFileSync(prefabFile, 'utf8'));
  } catch (error) {
    throw new Error(`${formatPath(prefabFile)} is not valid prefab JSON: ${error.message}`);
  }

  if (!Array.isArray(records)) {
    throw new Error(`${formatPath(prefabFile)} must be a Cocos serialized prefab array.`);
  }

  const rootId = findPrefabRootNodeId(records, prefabFile);
  const rootNode = readNode(records, rootId, prefabFile);
  const prefabName = path.basename(prefabFile, '.prefab');

  if (config.requireRootNameMatch && rootNode.name !== prefabName) {
    throw new Error(
      `${formatPath(prefabFile)} root node must be named '${prefabName}', actual '${rootNode.name}'.`,
    );
  }

  assertTypeScriptIdentifier(prefabName, `${formatPath(prefabFile)} prefab file name`);

  const errors = [];
  const bindings = [];

  walkNode(records, rootNode, [], prefabFile, config, bindings, errors);
  validateDuplicateFields(bindings, prefabFile, errors);

  if (errors.length > 0) {
    throw new Error(errors.join('\n'));
  }

  return {
    prefabFile,
    className: `${prefabName}Binding`,
    bindings,
  };
}

function findPrefabRootNodeId(records, prefabFile) {
  const prefabRecord = records.find((record) => getType(record) === 'cc.Prefab' || getType(record).endsWith('.Prefab'));
  if (prefabRecord && prefabRecord.data && Number.isInteger(prefabRecord.data.__id__)) {
    return prefabRecord.data.__id__;
  }

  const firstNodeIndex = records.findIndex((record) => getType(record) === 'cc.Node');
  if (firstNodeIndex >= 0) {
    return firstNodeIndex;
  }

  throw new Error(`${formatPath(prefabFile)} does not contain a cc.Node root.`);
}

function walkNode(records, node, pathSegments, prefabFile, config, bindings, errors) {
  const nodePath = pathSegments.join('/');

  if (node.name.length === 0) {
    errors.push(`${formatPath(prefabFile)} has an empty node name at '${nodePath || '<root>'}'.`);
  }

  if (node.name.includes('/')) {
    errors.push(`${formatPath(prefabFile)} node '${node.name}' cannot contain '/'.`);
  }

  if (pathSegments.length > 0) {
    const binding = tryCreateBinding(node, nodePath, prefabFile, config, errors);
    if (binding) {
      bindings.push(binding);
    }
  }

  const childNameMap = new Map();
  for (const childId of node.children) {
    const childNode = readNode(records, childId, prefabFile);
    const existingPath = childNameMap.get(childNode.name);
    const childPath = [...pathSegments, childNode.name].join('/');

    if (existingPath) {
      errors.push(
        `${formatPath(prefabFile)} has duplicate child node name '${childNode.name}' under '${nodePath || node.name}'.`,
      );
    } else {
      childNameMap.set(childNode.name, childPath);
    }

    walkNode(records, childNode, [...pathSegments, childNode.name], prefabFile, config, bindings, errors);
  }
}

function tryCreateBinding(node, nodePath, prefabFile, config, errors) {
  const match = findPrefixMatch(node.name, config.prefixes);
  if (!match) {
    return null;
  }

  const semanticName = node.name.slice(match.prefix.length).replace(/^[-_\s]+/, '');
  if (semanticName.length === 0) {
    errors.push(`${formatPath(prefabFile)} node '${nodePath}' uses prefix '${match.prefix}' without semantic name.`);
    return null;
  }

  if (match.component && match.component !== 'Node' && !nodeHasComponent(node, match.component)) {
    errors.push(
      `${formatPath(prefabFile)} node '${nodePath}' requires component '${match.component}' for prefix '${match.prefix}'.`,
    );
    return null;
  }

  const baseFieldName = toCamelCase(semanticName);
  if (baseFieldName.length === 0) {
    errors.push(`${formatPath(prefabFile)} node '${nodePath}' cannot generate a valid field name.`);
    return null;
  }

  const fieldName = appendSuffix(baseFieldName, match.fieldSuffix);
  assertTypeScriptIdentifier(fieldName, `${formatPath(prefabFile)} generated field '${fieldName}'`);

  return {
    fieldName,
    path: nodePath,
    type: match.type,
  };
}

function findPrefixMatch(nodeName, prefixes) {
  for (const entry of prefixes) {
    if (!nodeName.startsWith(entry.prefix)) {
      continue;
    }

    if (nodeName.length === entry.prefix.length) {
      return entry;
    }

    const next = nodeName.charAt(entry.prefix.length);
    if (next === '_' || next === '-' || next === ' ' || /[A-Z0-9]/.test(next)) {
      return entry;
    }
  }

  return null;
}

function validateDuplicateFields(bindings, prefabFile, errors) {
  const fields = new Map();
  for (const binding of bindings) {
    const existing = fields.get(binding.fieldName);
    if (existing) {
      errors.push(
        `${formatPath(prefabFile)} generated duplicate field '${binding.fieldName}' for '${existing}' and '${binding.path}'.`,
      );
      continue;
    }
    fields.set(binding.fieldName, binding.path);
  }
}

function readNode(records, id, prefabFile) {
  if (!Number.isInteger(id) || id < 0 || id >= records.length) {
    throw new Error(`${formatPath(prefabFile)} has invalid node reference id '${id}'.`);
  }

  const record = records[id];
  if (getType(record) !== 'cc.Node') {
    throw new Error(`${formatPath(prefabFile)} record '${id}' is not a cc.Node.`);
  }

  return {
    id,
    name: typeof record._name === 'string' ? record._name : '',
    children: readRefs(record._children),
    components: readRefs(record._components).map((componentId) => getType(records[componentId])),
  };
}

function readRefs(value) {
  if (!Array.isArray(value)) {
    return [];
  }

  return value
    .filter((item) => item && Number.isInteger(item.__id__))
    .map((item) => item.__id__);
}

function nodeHasComponent(node, componentType) {
  return node.components.some((type) => {
    if (type === componentType) {
      return true;
    }
    if (type === `cc.${componentType}`) {
      return true;
    }
    return type.endsWith(`.${componentType}`);
  });
}

function getType(record) {
  return record && typeof record.__type__ === 'string' ? record.__type__ : '';
}

function resolveOutputFile(prefabFile, config) {
  const root = findContainingRoot(prefabFile, config.prefabRoots);
  if (!root) {
    throw new Error(`${formatPath(prefabFile)} is not under configured prefabRoots.`);
  }

  const relativePrefabPath = path.relative(root, prefabFile);
  const parts = splitPath(relativePrefabPath);
  const prefabFileName = parts.pop();
  const moduleParts = parts;

  if (!prefabFileName || moduleParts.length === 0) {
    throw new Error(
      `${formatPath(prefabFile)} must be placed under a module folder, for example assets/prefabs/ui/hall/HallView.prefab.`,
    );
  }

  const viewName = path.basename(prefabFileName, '.prefab');
  return path.join(config.scriptOutputRoot, ...moduleParts, config.generatedDirName, `${viewName}Binding.generated.ts`);
}

function renderBindingFile(prefab, outputFile, config) {
  const outputDir = path.dirname(outputFile);
  const ccTypes = [...new Set(prefab.bindings.map((binding) => binding.type))].sort();
  const nodeBinderImport = toModuleImport(outputDir, config.nodeBinderPath);
  const baseViewImport = toModuleImport(outputDir, config.baseViewPath);
  const lines = [];

  lines.push(`// ${GENERATED_MARKER}`);
  lines.push('');
  if (ccTypes.length > 0) {
    lines.push(`import { ${ccTypes.join(', ')} } from 'cc';`);
  }
  lines.push(`import { NodeBinder } from '${nodeBinderImport}';`);
  lines.push(`import { UIView } from '${baseViewImport}';`);
  lines.push('');
  lines.push(`export abstract class ${prefab.className} extends UIView<void> {`);

  if (prefab.bindings.length > 0) {
    for (const binding of prefab.bindings) {
      lines.push(`  protected ${binding.fieldName}!: ${binding.type};`);
    }
    lines.push('');
  }

  lines.push('  protected bindNodes(): void {');
  if (prefab.bindings.length === 0) {
    lines.push('    return;');
  } else {
    for (const binding of prefab.bindings) {
      const nodeLookup = `NodeBinder.requiredNode(this.node, ${JSON.stringify(binding.path)})`;
      if (binding.type === 'Node') {
        lines.push(`    this.${binding.fieldName} = ${nodeLookup};`);
        continue;
      }

      lines.push(`    this.${binding.fieldName} = NodeBinder.requiredComponent(`);
      lines.push(`      ${nodeLookup},`);
      lines.push(`      ${binding.type},`);
      lines.push('    );');
    }
  }
  lines.push('  }');
  lines.push('}');
  lines.push('');

  return lines.join('\n');
}

function writeGeneratedFile(filePath, content, checkOnly, config) {
  const existing = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null;
  const changed = existing !== content;

  if (checkOnly) {
    if (changed) {
      throw new Error(`${formatPath(filePath)} is not up to date. Run npm run ui:generate.`);
    }
    return false;
  }

  if (!changed) {
    ensureTypeScriptMeta(filePath);
    return false;
  }

  ensureDirectoryWithMetas(path.dirname(filePath), config.scriptOutputRoot);
  fs.writeFileSync(filePath, content);
  ensureTypeScriptMeta(filePath);
  return true;
}

function handleStaleGeneratedFiles(config, expectedGeneratedFiles, args) {
  if (!fs.existsSync(config.scriptOutputRoot)) {
    return;
  }

  const generatedFiles = collectFiles(
    config.scriptOutputRoot,
    (filePath) => filePath.endsWith('Binding.generated.ts') && hasGeneratedMarker(filePath),
  );

  const staleFiles = generatedFiles.filter((filePath) => !expectedGeneratedFiles.has(filePath));
  if (staleFiles.length === 0) {
    return;
  }

  if (args.check) {
    throw new Error(
      `Stale UI binding file(s): ${staleFiles.map(formatPath).join(', ')}. Remove them or run npm run ui:generate -- --prune.`,
    );
  }

  if (!args.prune) {
    return;
  }

  for (const staleFile of staleFiles) {
    fs.unlinkSync(staleFile);
    const metaFile = `${staleFile}.meta`;
    if (fs.existsSync(metaFile)) {
      fs.unlinkSync(metaFile);
    }
    console.log(`[ui-binding] Pruned stale file ${formatPath(staleFile)}.`);
  }
}

function hasGeneratedMarker(filePath) {
  const raw = fs.readFileSync(filePath, 'utf8');
  return raw.includes(GENERATED_MARKER);
}

function ensureDirectoryWithMetas(dir, metaRoot) {
  fs.mkdirSync(dir, { recursive: true });

  const root = path.resolve(metaRoot);
  const relativeParts = splitPath(path.relative(root, dir));
  let cursor = root;

  for (const part of relativeParts) {
    cursor = path.join(cursor, part);
    ensureDirectoryMeta(cursor);
  }
}

function ensureDirectoryMeta(dir) {
  const metaPath = `${dir}.meta`;
  if (fs.existsSync(metaPath)) {
    return;
  }

  const meta = {
    ver: '1.2.0',
    importer: 'directory',
    imported: true,
    uuid: createUuid(),
    files: [],
    subMetas: {},
    userData: {},
  };

  fs.writeFileSync(metaPath, `${JSON.stringify(meta, null, 2)}\n`);
}

function ensureTypeScriptMeta(filePath) {
  const metaPath = `${filePath}.meta`;
  if (fs.existsSync(metaPath)) {
    return;
  }

  const meta = {
    ver: '4.0.24',
    importer: 'typescript',
    imported: true,
    uuid: createUuid(),
    files: [],
    subMetas: {},
    userData: {},
  };

  fs.writeFileSync(metaPath, `${JSON.stringify(meta, null, 2)}\n`);
}

function createUuid() {
  const bytes = crypto.randomBytes(16);
  bytes[6] = (bytes[6] & 0x0f) | 0x40;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;

  const hex = bytes.toString('hex');
  return [
    hex.slice(0, 8),
    hex.slice(8, 12),
    hex.slice(12, 16),
    hex.slice(16, 20),
    hex.slice(20),
  ].join('-');
}

function toCamelCase(input) {
  const cleaned = input.replace(/^[-_\s]+/, '').replace(/[-_\s]+$/g, '');
  if (cleaned.length === 0) {
    return '';
  }

  const words = cleaned.includes('_') || cleaned.includes('-') || /\s/.test(cleaned)
    ? cleaned.split(/[-_\s]+/).filter((word) => word.length > 0)
    : cleaned.match(/[A-Z]+(?=[A-Z][a-z]|\d|$)|[A-Z]?[a-z]+|\d+/g) || [cleaned];

  return words
    .map((word, index) => {
      const normalized = word.charAt(0).toUpperCase() + word.slice(1);
      return index === 0
        ? normalized.charAt(0).toLowerCase() + normalized.slice(1)
        : normalized;
    })
    .join('');
}

function appendSuffix(base, suffix) {
  const normalizedBase = base.toLowerCase();
  const normalizedSuffix = suffix.toLowerCase();
  if (normalizedBase.endsWith(normalizedSuffix)) {
    return base;
  }
  return `${base}${suffix}`;
}

function assertTypeScriptIdentifier(value, label) {
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value)) {
    throw new Error(`${label} must be a valid TypeScript identifier.`);
  }
}

function assertNonEmptyString(value, message) {
  if (typeof value !== 'string' || value.trim().length === 0) {
    throw new Error(message);
  }
  return value.trim();
}

function assertFileExists(filePath, message) {
  if (!fs.existsSync(filePath)) {
    throw new Error(`${message}: ${formatPath(filePath)}.`);
  }
}

function findContainingRoot(filePath, roots) {
  const normalizedFile = path.resolve(filePath);
  return roots.find((root) => {
    const relative = path.relative(root, normalizedFile);
    return relative.length > 0 && !relative.startsWith('..') && !path.isAbsolute(relative);
  }) || null;
}

function toModuleImport(fromDir, targetPath) {
  let relative = path.relative(fromDir, targetPath).replace(/\\/g, '/');
  relative = relative.replace(/\.ts$/, '');
  if (!relative.startsWith('.')) {
    relative = `./${relative}`;
  }
  return relative;
}

function splitPath(inputPath) {
  if (!inputPath) {
    return [];
  }
  return inputPath.split(/[\\/]+/).filter((part) => part.length > 0);
}

function resolveProjectPath(inputPath) {
  return path.resolve(process.cwd(), inputPath);
}

function formatPath(filePath) {
  return path.relative(process.cwd(), filePath).replace(/\\/g, '/');
}

main();
